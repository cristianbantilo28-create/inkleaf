"""Exports the trained CRNN to js/crnn-weights.js (int8 per output column, base64) and writes a test vector for the JS port.

  python3 export.py [ckpt.npz]
"""
import os, sys, json, base64, struct
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import gen, train

ck = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'out', 'ckpt.npz')
z = np.load(ck); meta = json.loads(str(z['__meta']))
Hn = meta['Hn']; chans = meta['chans']; layers = meta.get('layers', 1); pools = meta.get('pools', [list(p) for p in train.POOLS_V1])
names = []
for i in range(4): names += ['c%dw' % i, 'c%db' % i]
for k in range(layers):
    pre = train.lstm_names(k); names += [pre + 'fx', pre + 'fh', pre + 'fb', pre + 'bx', pre + 'bh', pre + 'bb']
names += ['ow', 'ob']
tensors = []; blobs = []
for n in names:
    a = np.asarray(z[n], np.float32)
    if a.ndim == 2:
        sc = np.maximum(np.abs(a).max(axis=0), 1e-8) / 127.0            # one scale per output column
        q = np.clip(np.round(a / sc[None, :]), -127, 127).astype(np.int8)
        tensors.append({'name': n, 'dtype': 'int8', 'shape': list(a.shape)}); blobs.append(q.tobytes() + sc.astype(np.float32).tobytes())
    else:
        tensors.append({'name': n, 'dtype': 'f32', 'shape': list(a.shape)}); blobs.append(a.astype(np.float32).tobytes())
header = json.dumps({'chars': gen.CHARS, 'Hn': Hn, 'chans': chans, 'layers': layers, 'pools': pools, 'step': meta.get('step'), 'wacc': meta.get('wacc'), 'cer': meta.get('cer'), 'tensors': tensors}).encode('utf-8')
out = bytearray(struct.pack('<I', len(header)) + header)
for b in blobs:
    out += b
    while len(out) % 4: out += b'\0'
b64 = base64.b64encode(bytes(out)).decode('ascii')
js = '/* Inkleaf — CRNN weights (int8), generated by tools/crnn/export.py. Step %s, synthetic word accuracy %.1f%%. */\n(function(){ const root = typeof window !== "undefined" ? window : self; (root.IL = root.IL || {}).crnnWeightsB64 = "%s"; })();\n' % (meta.get('step'), 100 * (meta.get('wacc') or 0), b64)
OUT_JS = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', '..', 'js', 'crnn-weights.js')
open(OUT_JS, 'w').write(js)
print('weights: %d KB binary, %d KB as JS' % (len(out) // 1024, len(js) // 1024))

# test vector: a synthetic sample through the numpy model (float weights) and through the quantized weights
m = train.model_from_meta(meta, gen.NCLASS); m.load(ck)
rng = np.random.default_rng(5)
X, labels, texts = gen.make_batch(rng, 1, width=None)
logits = m.forward(X, train=False)[0]
# quantized model for an apples-to-apples check
for n in names:
    a = np.asarray(z[n], np.float32)
    if a.ndim == 2:
        sc = np.maximum(np.abs(a).max(axis=0), 1e-8) / 127.0; m.P[n] = (np.clip(np.round(a / sc[None, :]), -127, 127) * sc[None, :]).astype(np.float32)
logits_q = m.forward(X, train=False)[0]
lp = logits_q - logits_q.max(axis=1, keepdims=True); lp = lp - np.log(np.exp(lp).sum(axis=1, keepdims=True))
json.dump({'text': texts[0], 'W': int(X.shape[2]), 'img': X[0].round(4).tolist(), 'logp': lp.round(4).tolist(), 'greedy_float': train.greedy_decode(logits[None])[0], 'greedy_q': train.greedy_decode(logits_q[None])[0]}, open(os.path.join(HERE, 'out', 'testvec.json'), 'w'))
print('test vector:', texts[0], '→ float:', train.greedy_decode(logits[None])[0], ' int8:', train.greedy_decode(logits_q[None])[0])
